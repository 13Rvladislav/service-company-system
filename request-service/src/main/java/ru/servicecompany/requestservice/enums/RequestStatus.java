
package ru.servicecompany.requestservice.enums;

/**
 * Статусы жизненного цикла заявки.
 *
 * Имена констант используются в PostgreSQL и JSON.
 * При переименовании статусов необходимо учитывать существующие
 * данные в базе и контракты между сервисами.
 */
public enum RequestStatus {

    /**
     * Заявка создана.
     */
    NEW,

    /**
     * Ожидается назначение мастера.
     */
    WAITING_FOR_ASSIGNMENT,

    /**
     * Мастер назначен и ожидает его решения.
     */
    ASSIGNED,

    /**
     * Мастер выполняет работы.
     */
    IN_PROGRESS,

    /**
     * Мастер отправил отчёт клиенту.
     */
    REPORT_SUBMITTED,

    /**
     * Клиент запросил доработку.
     */
    REVISION_REQUIRED,

    /**
     * Клиент принял работы, заявка закрыта.
     */
    COMPLETED,

    /**
     * Заявка отменена.
     */
    CANCELLED
}
